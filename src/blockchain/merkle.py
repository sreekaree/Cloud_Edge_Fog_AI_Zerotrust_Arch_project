"""Merkle Tree Implementation for MedTrustEdge Phase 5 Blockchain.

Calculates deterministic Merkle roots over ordered event hashes,
generates cryptographic inclusion proofs, and verifies audit paths.

Conventions:
- Leaf inputs are 64-character lowercase hex SHA-256 event hashes.
- Internal node hashing: SHA-256(left_hex + right_hex) with UTF-8 byte encoding.
- Odd leaf duplication: when a level contains an odd number of nodes (> 1),
  the last node is duplicated to form a complete pair.
- Empty tree root: SHA-256("") = e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855.
- Single-leaf root: for a single event [H_0], root is H_0; inclusion proof is empty list.
"""
from __future__ import annotations

import hashlib
import re
from typing import Any

HEX_64_REGEX = re.compile(r"^[0-9a-f]{64}$")
EMPTY_MERKLE_ROOT: str = hashlib.sha256(b"").hexdigest()


def is_valid_hex_hash(val: Any) -> bool:
    """Validates that a value is a 64-character lowercase hexadecimal hash."""
    return isinstance(val, str) and bool(HEX_64_REGEX.match(val))


class MerkleTreeError(Exception):
    """Base exception for Merkle tree errors."""


class InvalidLeafError(MerkleTreeError):
    """Raised when a leaf hash is malformed or invalid."""


class MerkleProofError(MerkleTreeError):
    """Raised when an inclusion proof cannot be generated or is malformed."""


class MerkleTree:
    """Binary Merkle tree constructed over an ordered sequence of event hashes."""

    def __init__(self, leaf_hashes: list[str] | tuple[str, ...]) -> None:
        self.leaves: list[str] = []
        for idx, leaf in enumerate(leaf_hashes):
            if not is_valid_hex_hash(leaf):
                raise InvalidLeafError(
                    f"Leaf at index {idx} is not a valid 64-char lowercase hex hash: '{leaf}'"
                )
            self.leaves.append(leaf.lower())

        self.levels: list[list[str]] = []
        self._build_tree()

    def _build_tree(self) -> None:
        """Constructs all levels of the binary Merkle tree from leaves to root."""
        if not self.leaves:
            self.levels = [[]]
            self.root: str = EMPTY_MERKLE_ROOT
            return

        if len(self.leaves) == 1:
            self.levels = [[self.leaves[0]]]
            self.root = self.leaves[0]
            return

        current_level = list(self.leaves)
        self.levels = [current_level]

        while len(current_level) > 1:
            # Duplicate the last node if the count is odd
            padded_level = list(current_level)
            if len(padded_level) % 2 == 1:
                padded_level.append(padded_level[-1])

            next_level: list[str] = []
            for i in range(0, len(padded_level), 2):
                combined = (padded_level[i] + padded_level[i + 1]).encode("utf-8")
                parent_hash = hashlib.sha256(combined).hexdigest()
                next_level.append(parent_hash)

            self.levels.append(next_level)
            current_level = next_level

        self.root = self.levels[-1][0]

    def get_root(self) -> str:
        """Returns the 64-character hexadecimal Merkle root."""
        return self.root

    def get_inclusion_proof(self, index: int) -> list[dict[str, str]]:
        """Generates an audit inclusion proof for the leaf at the specified index.

        Returns:
            list[dict[str, str]]: Ordered list of steps with 'direction' ('left' or 'right')
            and 'hash' (the sibling's hex hash).
        """
        if not isinstance(index, int) or index < 0 or index >= len(self.leaves):
            raise IndexError(f"Leaf index {index} out of range for tree with {len(self.leaves)} leaves")

        if len(self.leaves) == 1:
            return []

        proof: list[dict[str, str]] = []
        curr_idx = index

        for level_idx in range(len(self.levels) - 1):
            level = self.levels[level_idx]
            padded_level = list(level)
            if len(padded_level) % 2 == 1:
                padded_level.append(padded_level[-1])

            if curr_idx % 2 == 0:
                sibling_idx = curr_idx + 1
                direction = "right"
            else:
                sibling_idx = curr_idx - 1
                direction = "left"

            sibling_hash = padded_level[sibling_idx]
            proof.append({"direction": direction, "hash": sibling_hash})
            curr_idx = curr_idx // 2

        return proof


def verify_inclusion_proof(leaf_hash: str, proof: list[dict[str, str]], expected_root: str) -> bool:
    """Verifies an audit inclusion proof against an expected Merkle root.

    Args:
        leaf_hash: The 64-char hex hash of the leaf to verify.
        proof: Sibling proof path generated by MerkleTree.get_inclusion_proof().
        expected_root: The expected 64-char hex Merkle root.

    Returns:
        bool: True if proof recalculates to expected_root, False otherwise.
    """
    if not is_valid_hex_hash(leaf_hash) or not is_valid_hex_hash(expected_root):
        return False

    if not proof:
        return leaf_hash.lower() == expected_root.lower()

    current_hash = leaf_hash.lower()
    for step in proof:
        direction = step.get("direction")
        sibling = step.get("hash")
        if direction not in ("left", "right") or not is_valid_hex_hash(sibling):
            return False

        sibling = sibling.lower()
        if direction == "right":
            combined = (current_hash + sibling).encode("utf-8")
        else:
            combined = (sibling + current_hash).encode("utf-8")

        current_hash = hashlib.sha256(combined).hexdigest()

    return current_hash == expected_root.lower()
